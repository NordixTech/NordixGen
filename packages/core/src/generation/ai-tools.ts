import type { ResolvedInput } from "../project/types.js";

function toolInput(input: ResolvedInput): string {
  const field = input.definition;
  let value: string;
  switch (field.type) {
    case "string":
      value = `z.string()${field.minLength === undefined ? "" : `.min(${field.minLength})`}${field.maxLength === undefined ? "" : `.max(${field.maxLength})`}`;
      break;
    case "uuid":
      value = "z.string().uuid()";
      break;
    case "date":
      value = "z.string().datetime({offset:true})";
      break;
    case "number":
      value = `z.number().finite()${field.format === "integer" ? ".int()" : ""}`;
      break;
    case "boolean":
      value = "z.boolean()";
      break;
    case "json":
      value = "jsonValue";
      break;
    case "enum":
      value = `z.enum(${JSON.stringify(field.value.enumValues)})`;
      break;
  }
  if (input.array) value = `z.array(${value}).min(1)`;
  if (input.nullable) value += ".nullable()";
  if (input.optional) value += ".optional()";
  return value;
}
export function aiToolFiles(context: BackendRenderContext): GeneratedFile[] {
  const root = `${context.platformRoot}/ai`;
  const operations = context.domainModel.endpoints;
  const imports = operations.map((operation, index) => {
    const module = context.domainModel.modules.find(
      (module) => module.id === operation.moduleId,
    ) as BackendRenderContext["domainModel"]["modules"][number];
    const layout = resolveArchitectureLayout(module.architecture);
    const target = posix.join(
      context.moduleRoots[module.id],
      layout.directories.useCase,
      "dtos/endpoints",
      `${operation.typeName}.dto.js`,
    );
    return `import {InputSchema as input${index}} from ${JSON.stringify(posix.relative(root, target))};`;
  });
  return [
    { path: `${root}/define-tool.ts`, content: defineToolSource },
    {
      path: `${root}/custom-tools.ts`,
      content:
        "// Generated by scripts/discover-tools.mjs before development, checks and builds.\nexport default [];\n",
    },
    {
      path: `${context.framework.applicationRoot}/scripts/discover-tools.mjs`,
      content: discoverToolsSource,
    },
    {
      path: `${root}/generated-tools.ts`,
      content: [
        'import {z} from "zod";',
        'import {defineTool} from "./define-tool.js";',
        ...imports,
        "type Json=string|number|boolean|null|Json[]|{[key:string]:Json};const jsonValue:z.ZodType<Json>=z.lazy(()=>z.union([z.string(),z.number().finite(),z.boolean(),z.null(),z.array(jsonValue),z.record(jsonValue)]));void jsonValue;",
        "export const generatedTools=[",
        ...operations.map((operation, index) => {
          const module = context.domainModel.modules.find(
            (module) => module.id === operation.moduleId,
          ) as BackendRenderContext["domainModel"]["modules"][number];
          return `defineTool({name:${JSON.stringify(`${module.name.replaceAll("-", "_")}_${operation.operationId}`)},description:${JSON.stringify(`Tool ${module.name.replaceAll("-", "_")}_${operation.operationId}. ${operation.summary ?? `${operation.operationId.replace(/([a-z])([A-Z])/g, "$1 $2")}: ${context.domainModel.entities[operation.entity].description ?? operation.entity}`}`)},permissions:${JSON.stringify(operation.permissions)},isDestructive:${operation.method !== "GET"},schema:z.object({${Object.values(
            operation.input,
          )
            .map((input) => `${JSON.stringify(input.name)}:${toolInput(input)}`)
            .join(
              ",",
            )}}).strict(),operationId:${JSON.stringify(operation.operationId)},module:${JSON.stringify(module.name)},audit:${Boolean(operation.audit)},execute:async(input,ctx)=>{
 const value=input${index}.parse({...input,${Object.values(operation.input)
   .filter((input) => input.definition.type === "date")
   .map(
     (input) =>
       `${JSON.stringify(input.name)}:input[${JSON.stringify(input.name)}]==null?input[${JSON.stringify(input.name)}]:${input.array ? `(input[${JSON.stringify(input.name)}] as string[]).map(value=>new Date(value))` : `new Date(input[${JSON.stringify(input.name)}] as string)`}`,
   )
   .join(",")}});
 return ctx.invoke(${JSON.stringify(module.name)},${JSON.stringify(operation.operationId)},value);
}}),`;
        }),
        "];",
        "",
      ].join("\n"),
    },
  ];
}
export const defineToolSource = `import type {z} from "zod";
import type {Principal,OperationContext} from "../application/contracts.js";
export interface ToolContext {readonly principal:Principal;readonly operationContext:OperationContext;readonly signal:AbortSignal;invoke(module:string,operation:string,input:unknown):Promise<unknown>;}
export interface AppTool {name:string;description:string;permissions:readonly string[];isDestructive:boolean;schema:z.ZodTypeAny;operationId?:string;module?:string;audit?:boolean;execute(input:unknown,context:ToolContext):Promise<unknown>;}
export function defineTool<T extends z.ZodTypeAny>(definition:{name:string;description:string;permission?:string;permissions?:readonly string[];isDestructive:boolean;schema:T;operationId?:string;module?:string;audit?:boolean;execute(input:z.output<T>,context:ToolContext):Promise<unknown>}):AppTool {
 if(!/^[a-zA-Z0-9_-]{1,64}$/.test(definition.name))throw Error("Tool names must contain 1-64 letters, digits, underscores or hyphens.");
 return Object.freeze({...definition,permissions:Object.freeze([...(definition.permissions??(definition.permission?[definition.permission]:[]))])});
}
`;
const discoverToolsSource = `import {readdir,readFile,writeFile} from "node:fs/promises";
import {join,relative,resolve} from "node:path";
import ts from "typescript";
const target=resolve("src/platform/ai/custom-tools.ts");
async function walk(dir){const result=[];for(const entry of await readdir(dir,{withFileTypes:true})){const path=join(dir,entry.name);if(entry.isDirectory())result.push(...await walk(path));else if(entry.isFile()&&entry.name.endsWith(".tool.ts"))result.push(path);}return result;}
const imports=[],names=[];
for(const file of (await walk("src")).sort()){
 const source=ts.createSourceFile(file,await readFile(file,"utf8"),ts.ScriptTarget.Latest,true);
 for(const statement of source.statements){
  if(!ts.isVariableStatement(statement)||!statement.modifiers?.some(modifier=>modifier.kind===ts.SyntaxKind.ExportKeyword))continue;
  for(const declaration of statement.declarationList.declarations){
   if(!ts.isIdentifier(declaration.name)||!declaration.initializer||!ts.isCallExpression(declaration.initializer)||!ts.isIdentifier(declaration.initializer.expression)||declaration.initializer.expression.text!=="defineTool")continue;
   const name="custom"+names.length;names.push(name);
   let path=relative(resolve("src/platform/ai"),resolve(file)).replaceAll("\\\\","/").replace(/\\.ts$/,".js");if(!path.startsWith("."))path="./"+path;
   imports.push("import {"+declaration.name.text+" as "+name+"} from "+JSON.stringify(path)+";");
  }
 }
}
await writeFile(target,imports.join("\\n")+"\\nexport default ["+names.join(",")+"];\\n");
`;
