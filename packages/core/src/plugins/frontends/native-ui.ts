        'import { Button } from "./button";',
        "",
        "export interface DialogProps {",
        "  open: boolean;",
        "  title: string;",
        "  description?: string;",
        "  onOpenChange: (open: boolean) => void;",
        "  children: ReactNode;",
        "}",
        "",
        "export function Dialog({ open, title, description, onOpenChange, children }: DialogProps) {",
        "  const dialogRef = useRef<HTMLDialogElement>(null);",
        "  const titleId = useId();",
        "  const descriptionId = useId();",
        "",
        "  useEffect(() => {",
        "    const dialog = dialogRef.current;",
        "    if (!dialog) return;",
        "    if (open && !dialog.open) {",
        "      dialog.showModal();",
        '      dialog.querySelector<HTMLElement>("[data-initial-focus]")?.focus();',
        "    }",
        "    if (!open && dialog.open) dialog.close();",
        "  }, [open]);",
        "",
        "  return (",
        "    <dialog",
        "      aria-describedby={description ? descriptionId : undefined}",
        "      aria-labelledby={titleId}",
        '      className="ng-dialog"',
        "      onCancel={(event) => {",
        "        event.preventDefault();",
        "        onOpenChange(false);",
        "      }}",
        "      onClose={() => onOpenChange(false)}",
        "      ref={dialogRef}",
        "    >",
        '      <div className="ng-dialog-heading">',
        "        <div>",
        "          <h2 id={titleId}>{title}</h2>",
        "          {description ? <p id={descriptionId}>{description}</p> : null}",
        "        </div>",
        '        <Button aria-label="Close dialog" onClick={() => dialogRef.current?.close()} variant="secondary">×</Button>',
        "      </div>",
        '      <div className="ng-dialog-content">{children}</div>',
        "    </dialog>",
        "  );",
        "}",
